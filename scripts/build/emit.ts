/**
 * Generated-output emission for content:build.
 *
 * Writes everything under `src/generated/content/**`, `src/generated/content-index.ts`,
 * the per-kind `*-loaders.ts` manifests, and `public/papers-index.json` +
 * `src/generated/papers-index.ts`. The five content kinds that share this shape
 * (blog, algorithm, demo, model, concept) are driven off `HTML_LOADER_KIND_DESCRIPTORS`
 * (scripts/lib/content-kinds.ts) rather than five separate copy-pasted blocks;
 * narratives have their own richer per-module shape (see narrative-build.ts) and
 * are handled alongside, not through the same table.
 */
import { writeFileSync, existsSync, mkdirSync, rmSync, readdirSync } from "node:fs";
import { join } from "node:path";

import type {
    BlogEntry,
    AlgorithmEntry,
    DemoEntry,
    ModelEntry,
    ConceptEntry,
    BlogIndexEntry,
    AlgorithmIndexEntry,
    DemoIndexEntry,
    ModelIndexEntry,
    ConceptIndexEntry,
    NarrativeEntry,
    NarrativeIndexEntry,
} from "../../src/lib/content/schema.ts";
import { buildNarrativeIndexEntry, emitNarrativeModule, emitNarrativeLoaders } from "../narrative-build.ts";
import { HTML_LOADER_KIND_DESCRIPTORS } from "../lib/content-kinds.ts";
import type { HtmlLoaderKindDescriptor } from "../lib/content-kinds.ts";
import { GENERATED_DIR, PUBLIC_DIR } from "../lib/paths.ts";
import type { PaperRefRecord } from "../lib/papers-index.ts";

/** Removes every generated `.ts` html module in `dir` (a stale-slug cleanup ahead of a fresh write). */
export function cleanGeneratedHtmlModules(dir: string): void {
    if (!existsSync(dir)) return;
    for (const file of readdirSync(dir)) {
        if (file.endsWith(".ts")) {
            rmSync(join(dir, file));
        }
    }
}

function emitHtmlModules(entries: { slug: string; html: string }[], dir: string): void {
    for (const entry of entries) {
        const file = join(dir, `${entry.slug}.ts`);
        writeFileSync(file, `// Auto-generated — do not edit manually.\nexport const html = ${JSON.stringify(entry.html)};\n`, "utf-8");
    }
}

function emitLoaderManifest(descriptor: HtmlLoaderKindDescriptor, slugs: string[], outDir: string): void {
    const lines = [
        "// Auto-generated by scripts/content-build.ts — do not edit manually.",
        "export interface GeneratedHtmlModule { html: string; }",
        "",
        `export const ${descriptor.loaderExportName}: Record<string, () => Promise<GeneratedHtmlModule>> = {`,
        ...slugs.map((slug) => `  ${JSON.stringify(slug)}: () => import(${JSON.stringify(`./content/${descriptor.htmlDirName}/${slug}.ts`)}),`),
        "};",
        "",
    ];
    writeFileSync(join(outDir, descriptor.loaderFileName), lines.join("\n"), "utf-8");
}

function toIndexEntries<E extends { slug: string; frontmatter: unknown }>(
    entries: E[],
): { slug: string; frontmatter: E["frontmatter"] }[] {
    return entries.map(({ slug, frontmatter }) => ({ slug, frontmatter }));
}

export interface GenerateOutputInput {
    blogPosts: BlogEntry[];
    algorithmPages: AlgorithmEntry[];
    demoPages: DemoEntry[];
    modelPages: ModelEntry[];
    conceptPages: ConceptEntry[];
    /** Published-only subsets (excludes dev:true pages). Used for index + search listings only. */
    algorithmPublished: AlgorithmEntry[];
    modelPublished: ModelEntry[];
    conceptPublished: ConceptEntry[];
    /** Fully resolved narratives (html + chapters + narrative graph). No separate "published" subset — narratives have no `dev` flag. */
    narrativePages: NarrativeEntry[];
}

export function generateOutput(input: GenerateOutputInput): void {
    const {
        blogPosts,
        algorithmPages,
        demoPages,
        modelPages,
        conceptPages,
        algorithmPublished,
        modelPublished,
        conceptPublished,
        narrativePages,
    } = input;

    if (!existsSync(GENERATED_DIR)) mkdirSync(GENERATED_DIR, { recursive: true });

    // 1. Per-slug html modules for lazy client-side loading — routable set, dev
    // pages included (they stay directly reachable by URL, just not listed).
    const kindGroups: { descriptor: HtmlLoaderKindDescriptor; entries: { slug: string; html: string }[] }[] = [
        { descriptor: HTML_LOADER_KIND_DESCRIPTORS.blog, entries: blogPosts },
        { descriptor: HTML_LOADER_KIND_DESCRIPTORS.algorithm, entries: algorithmPages },
        { descriptor: HTML_LOADER_KIND_DESCRIPTORS.demo, entries: demoPages },
        { descriptor: HTML_LOADER_KIND_DESCRIPTORS.model, entries: modelPages },
        { descriptor: HTML_LOADER_KIND_DESCRIPTORS.concept, entries: conceptPages },
    ];

    for (const { descriptor, entries } of kindGroups) {
        const dir = join(GENERATED_DIR, "content", descriptor.htmlDirName);
        if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
        cleanGeneratedHtmlModules(dir);
        emitHtmlModules(entries, dir);
    }

    const narrativeHtmlDir = join(GENERATED_DIR, "content", "narratives");
    if (!existsSync(narrativeHtmlDir)) mkdirSync(narrativeHtmlDir, { recursive: true });
    cleanGeneratedHtmlModules(narrativeHtmlDir);
    for (const narrative of narrativePages) {
        emitNarrativeModule(narrative, narrativeHtmlDir);
    }

    // 2. Metadata-only index (no html) — dev:true pages excluded from all indexes.
    const blogIndex: BlogIndexEntry[] = toIndexEntries(blogPosts);
    const algoIndex: AlgorithmIndexEntry[] = toIndexEntries(algorithmPublished);
    const demoIndex: DemoIndexEntry[] = toIndexEntries(demoPages);
    const modelIndex: ModelIndexEntry[] = toIndexEntries(modelPublished);
    const conceptIndex: ConceptIndexEntry[] = toIndexEntries(conceptPublished);
    // Narratives have no separate {slug, frontmatter} wrapper — the index entry is
    // a slim, flattened NarrativeIndexEntry (see CLAUDE.md-adjacent design in schema.ts).
    const narrativeIndex: NarrativeIndexEntry[] = narrativePages.map((e) =>
        buildNarrativeIndexEntry(e.slug, e.frontmatter, e.narrative, e.frontmatter.steps.length),
    );

    const indexLines = [
        '// Auto-generated by scripts/content-build.ts — do not edit manually.',
        'import type { BlogIndexEntry, AlgorithmIndexEntry, DemoIndexEntry, ModelIndexEntry, ConceptIndexEntry, NarrativeIndexEntry } from "../lib/content/schema.ts";',
        "",
        `export const blogPosts: BlogIndexEntry[] = ${JSON.stringify(blogIndex, null, 2)};`,
        "",
        `export const algorithmPages: AlgorithmIndexEntry[] = ${JSON.stringify(algoIndex, null, 2)};`,
        "",
        `export const demoPages: DemoIndexEntry[] = ${JSON.stringify(demoIndex, null, 2)};`,
        "",
        `export const modelPages: ModelIndexEntry[] = ${JSON.stringify(modelIndex, null, 2)};`,
        "",
        `export const conceptPages: ConceptIndexEntry[] = ${JSON.stringify(conceptIndex, null, 2)};`,
        "",
        `export const narrativePages: NarrativeIndexEntry[] = ${JSON.stringify(narrativeIndex, null, 2)};`,
        "",
    ];
    const indexFile = join(GENERATED_DIR, "content-index.ts");
    writeFileSync(indexFile, indexLines.join("\n"), "utf-8");

    // 3. Explicit slug-to-loader manifests so client code never relies on fragile glob keys.
    for (const { descriptor, entries } of kindGroups) {
        emitLoaderManifest(descriptor, entries.map((e) => e.slug), GENERATED_DIR);
    }

    // Narrative loader manifest — richer per-module shape (html + chapters + narrative
    // graph), so it gets its own interface rather than reusing GeneratedHtmlModule.
    emitNarrativeLoaders(narrativePages.map(({ slug }) => ({ slug })), GENERATED_DIR);
}

export function emitPapersIndex(papers: PaperRefRecord[], usedPrimaryIds: Set<string>): void {
    const known = new Set(papers.map((p) => p.id));
    const missing = [...usedPrimaryIds].filter((id) => !known.has(id)).sort();
    if (missing.length > 0) {
        console.warn(
            `content:build — ${missing.length} primary source ID(s) referenced by pages are not in docs/papers/index.yaml: ${missing.join(", ")}`,
        );
    }

    // Emit the lookup as a static JSON asset under public/ so Vite serves it
    // verbatim from /papers-index.json. This keeps ~16 kB of paper metadata
    // out of the main JS bundle; the client lazy-fetches it once on demand.
    const papersById = Object.fromEntries(papers.map((p) => [p.id, p]));
    const jsonPath = join(PUBLIC_DIR, "papers-index.json");
    writeFileSync(jsonPath, JSON.stringify(papersById, null, 2), "utf-8");

    // Tiny TS shim: re-exports the type so the rest of the codebase has a single
    // source of truth, but ships no data.
    const tsLines = [
        "// Auto-generated by scripts/content-build.ts — do not edit manually.",
        "// The actual paper records live in /papers-index.json (loaded lazily).",
        "",
        'import type { PaperRef, PapersById } from "../lib/atlas/paperRefTypes.ts";',
        "",
        "export type { PaperRef, PapersById };",
        "",
        "/** Public URL of the JSON asset emitted by content:build. */",
        'export const PAPERS_INDEX_URL = "/papers-index.json";',
        "",
    ];
    writeFileSync(join(GENERATED_DIR, "papers-index.ts"), tsLines.join("\n"), "utf-8");
}
